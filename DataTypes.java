
public class DataTypes {
    public static void main(String[] args) {
	
	//
	System.out.println("I'm Saran");
	System.out.print("B.E CSE\n");
	byte a = 10;
	System.out.println(a + "\n");

	//PRIMITIVE DATA TYPES
		
        int age = 20;
		long population = 7800000000L;
		short year = 2024;
		byte level = 5;
		float pi = 3.14f;
        double marks = 89.5;
        char grade = 'A';
        boolean passed = true;

	//NON-PRIMITIVE DATA TYPES
        String name = "Saran";
        int[] numbers = {10, 20, 30};

        System.out.println("Int: " + age);
		System.out.println("Long: " + population);
		System.out.println("Short: " + year);
        System.out.println("Byte: " + level);
		System.out.println("Flote: " + pi);
		System.out.println("Double: " + marks);
        System.out.println("Char: " + grade);
        System.out.println("Boolean: " + passed);
        System.out.println("String: " + name);
        System.out.println("Array: " + numbers[0]);
    }
}